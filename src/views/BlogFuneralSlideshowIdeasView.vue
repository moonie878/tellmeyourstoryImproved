        <h2 class="article-h2 mt-12">Words and text ideas for a funeral slideshow</h2>
        <p class="article-p">Most funeral slideshows include some text — their name and dates, a quote, or a short tribute. Here are ideas for making the words count.</p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">Open with their full name and dates</p>
            <p class="tip-desc">A simple title slide with their name, birth year, and year of passing is a dignified and clear opening. It tells everyone in the room whose life they're about to see.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Include a short tribute in their memory</p>
            <p class="tip-desc">A paragraph or two about who they were — what they loved, how they made people feel, what they gave to those around them. This becomes a quote slide that appears naturally within the video. Keep it honest and specific rather than general and formal.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Use something they actually said</p>
            <p class="tip-desc">A saying they always used, a piece of advice they gave, a joke they told. Something in their own voice is worth more than any professional tribute. Ask family members — someone will remember something.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">A poem or quote if it fits</p>
            <p class="tip-desc">Not all funerals need a quote, and a generic one does more harm than good. But if there's a poem or line that genuinely meant something to them or to the family — Mary Oliver, Rumi, or something more personal — it can be the most moving moment in the slideshow.</p>
          </div>
        </div>

        <h2 class="article-h2 mt-12">Structure ideas — how to order a funeral slideshow</h2>
        <p class="article-p">The order of photos matters as much as the photos themselves. Here are three structures that work.</p>

        <div class="mt-6 space-y-6">
          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">Structure 1 — Chronological (most common)</h3>
            <p class="article-p mt-2">Start with childhood and work forward through their life. This is the most natural structure — it tells the story of a life from beginning to end and gives the slideshow a clear emotional arc. Most people in the room will recognise different chapters at different moments.</p>
          </div>
          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">Structure 2 — By relationship</h3>
            <p class="article-p mt-2">Organise photos by the relationships that defined their life — as a child, as a partner, as a parent, as a friend, as a grandparent. This works particularly well when you want to honour different sides of who they were to different people in the room.</p>
          </div>
          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">Structure 3 — Open with the best, close with the best</h3>
            <p class="article-p mt-2">Put your most striking photo first and your warmest photo last. Fill the middle chronologically or thematically. The first and last photos are the ones people will carry with them — make sure they're the right ones.</p>
          </div>
        </div>

        <h2 class="article-h2 mt-12">Practical ideas for showing the slideshow at the service</h2>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">Play it before the service begins</p>
            <p class="tip-desc">Many families play the slideshow on a loop as people arrive and take their seats. This sets a warm, reflective tone before the service starts and gives people something to watch while they wait.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Play it as a dedicated moment during the service</p>
            <p class="tip-desc">The funeral director or celebrant introduces it: "We're going to take a few minutes to remember [Name] through some of the photos that meant the most to the family." Then the room goes quiet and watches together. This is often the most moving moment in the entire service.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Play it at the wake</p>
            <p class="tip-desc">A funeral service is often formal and time-pressured. The wake is where people relax, talk, and remember. Playing the slideshow quietly on a screen in the corner of the wake venue gives people something to gather around and talk about.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Share it with family who couldn't attend</p>
            <p class="tip-desc">After downloading your tribute video, send the MP4 file to family members who couldn't be at the service. Upload it to a private YouTube link or a shared Google Drive folder so everyone can watch it in their own time.</p>
          </div>
