        <h2 class="article-h2 mt-12">Photo ideas for a funeral slideshow</h2>
        <p class="article-p">The photos you choose make or break a funeral slideshow. Here's what to look for and how to organise them.</p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">One photo from each decade of their life</p>
            <p class="tip-desc">This is the simplest structure that works every time. Find one strong photo from their childhood, one from their teens, one from their twenties, and so on. It creates a natural journey through a life without requiring too many photos or too much organisation.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Photos with the people who matter most</p>
            <p class="tip-desc">Photos of them with their partner, their children, their parents, their closest friends. These land hardest because they show the relationships — the love — not just the person in isolation.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Photos of them doing what they loved</p>
            <p class="tip-desc">In the garden, at a football match, cooking in the kitchen, on holiday, with a pet. Photos that show their character — what made them them — rather than just formal portraits.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">At least one photo people haven't seen before</p>
            <p class="tip-desc">A childhood photo, a photo from before they were a parent, a photo from a part of their life most people didn't know. These are the ones that make people gasp quietly — the recognition that there was a whole person before the role they played in everyone's lives.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">A photo that shows their sense of humour</p>
            <p class="tip-desc">If they were funny — and most people are, in their own way — include one photo that shows it. A photo of them laughing, or in a silly moment, gives people permission to smile as well as cry. That's a gift.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">The most recent good photo you have</p>
            <p class="tip-desc">Don't skip over the later years because the photos are harder to find or people look older. A recent photo of them, warm and present, is one of the most important images to include. It's the version of them that people in the room knew best.</p>
          </div>
        </div>

        <h2 class="article-h2 mt-12">Music ideas for a funeral slideshow</h2>
        <p class="article-p">Music carries more emotional weight than any other element of a funeral slideshow. The right song can transform a room. Here are ideas for choosing well.</p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">A song from their era</p>
            <p class="tip-desc">Music from someone's youth is deeply tied to memory and identity. A song from the 1960s, 70s, or 80s that they would have loved as a young person immediately takes people back — and creates a connection to who they were before anyone in the room knew them.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Their wedding song</p>
            <p class="tip-desc">If you know it, this is one of the most powerful choices. It connects the slideshow to one of the defining moments of their life and honours the relationship at the heart of their family.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">A song they always had on</p>
            <p class="tip-desc">The song that was always playing in their car, their kitchen, their living room. Something so associated with them that hearing it immediately brings them to mind. Ask family members — someone will know.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Instrumental if you're unsure</p>
            <p class="tip-desc">If you can't identify a specific meaningful song, choose an instrumental piece — gentle piano, a string arrangement, something warm and slow. Instrumental music supports the photos without competing with people's thoughts and emotions. Search "gentle piano memorial" on Spotify or YouTube for ideas.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">One song only</p>
            <p class="tip-desc">For most funeral slideshows, one song is enough. Multiple tracks create jarring transitions and interrupt the emotional flow. If your slideshow runs longer than one song, let the song loop quietly rather than switching to something different.</p>
          </div>
        </div>

