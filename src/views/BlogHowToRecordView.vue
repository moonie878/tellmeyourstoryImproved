        </p>
        <p class="article-p mt-4">
          Here's what tends to work:
        </p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">Start with facts, not feelings</p>
            <p class="tip-desc">"What was your first job?" is easier to answer than "What were your dreams when you were young?" Start with concrete, factual questions. The emotional stuff often surfaces naturally once they're talking.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Use photos as a doorway</p>
            <p class="tip-desc">An old family photo is one of the most powerful memory triggers there is. "Who's this?" or "What was happening here?" can open up a conversation that runs for hours.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Tell them why it matters to you</p>
            <p class="tip-desc">"I want to know your story. I want to write it down so we don't lose it." Most parents find this deeply moving — the idea that someone genuinely wants to preserve their life. Say it plainly.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Let them write instead of talk</p>
            <p class="tip-desc">Some people find writing far easier than speaking about personal things. Give them the questions and let them answer in their own time, in their own words, without an audience.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Accept partial answers</p>
            <p class="tip-desc">Not every question will get a full answer. Some things are private. Some memories are painful. Accept what they give you and don't push. The trust you build by not pushing is what opens the door to the harder questions later.</p>
          </div>
