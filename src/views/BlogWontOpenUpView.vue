        <div class="founder-note">
          <p class="founder-text">
            The most common thing people tell me when they sign up to Tell Me Your Story isn't "I can't wait to start." It's "I'm not sure my parent will actually answer anything."
          </p>
          <p class="founder-text mt-4">
            They're worried their dad will shrug and say "there's nothing interesting about me." Or their mum will deflect every question with "oh, you don't want to hear about all that." Or they'll get one-word answers and then silence.
          </p>
          <p class="founder-text mt-4">
            This is the most common obstacle to capturing a parent's life story — not equipment, not time, not knowing what to ask. It's the parent themselves.
          </p>
          <p class="founder-text mt-4 font-medium text-[#1C1917]">
            But here's what I've learned: most parents who "won't open up" will — with the right approach. This guide is about finding that approach.
          </p>
        </div>

        <!-- Section 1 -->
        <h2 class="article-h2 mt-12">Why parents don't volunteer their stories</h2>
        <p class="article-p">
          Before you can unlock a parent's story, it helps to understand why they're holding back in the first place. It's rarely what you think.
        </p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">"Nobody has ever asked me"</p>
            <p class="tip-desc">This is the most common reason of all. Many parents — especially older ones — have simply never been asked about their lives in any meaningful way. They assume nobody is interested. The moment someone asks, that assumption dissolves.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">"My life isn't interesting enough"</p>
            <p class="tip-desc">Most parents genuinely believe this. They compare their ordinary life to what they see on TV or read about and conclude that nobody would want to hear about it. They're wrong — but they need to be shown that, not told.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">"I don't want to burden you"</p>
            <p class="tip-desc">Particularly common with parents who went through difficult times — illness, poverty, loss, things they've never talked about. They've protected their children from these things for decades. Old habits are hard to break.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">"Talking about myself feels uncomfortable"</p>
            <p class="tip-desc">Generational and cultural. Many parents — fathers especially — grew up in an era where talking about yourself was considered self-indulgent or even weak. They need a different kind of invitation.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">"I don't know where to start"</p>
            <p class="tip-desc">"Tell me about your life" is an overwhelming question. The whole life? From the beginning? Most people freeze when faced with something that big. A specific, small question is much easier to answer.</p>
          </div>
        </div>

        <!-- Section 2 -->
        <h2 class="article-h2 mt-12">The single most important thing you can do</h2>
        <p class="article-p">
          Before any technique or question or approach — do this first.
        </p>
        <p class="article-p mt-4">
          Tell them, plainly and directly, why you want to know.
        </p>
        <p class="article-p mt-4">
          Not as a preamble to a question. Not hinted at. Said out loud, clearly, in a way they can't deflect:
        </p>

        <div class="mt-6 rounded-2xl bg-[#FAF7F4] border border-[#E8DDD0] px-6 py-6">
          <p class="text-sm font-medium text-[#1C1917] mb-4">Things worth saying out loud:</p>
          <div class="space-y-3">
            <p class="text-sm text-[#3C3530] italic border-l-2 border-[#C4A882] pl-4">"I want to know your story. I want to write it down so we don't lose it."</p>
            <p class="text-sm text-[#3C3530] italic border-l-2 border-[#C4A882] pl-4">"I realised I don't actually know what your life was like before I was born. I want to change that."</p>
            <p class="text-sm text-[#3C3530] italic border-l-2 border-[#C4A882] pl-4">"I want our kids to know who you really were. Not just as a grandparent — as a person."</p>
            <p class="text-sm text-[#3C3530] italic border-l-2 border-[#C4A882] pl-4">"I don't want to look back and realise I never asked."</p>
          </div>
        </div>

        <p class="article-p mt-6">
          Most parents find this deeply moving. The idea that someone genuinely wants to know — not out of obligation, but because they care — changes everything. It reframes the whole conversation from an interview into something much more meaningful.
        </p>
        <p class="article-p mt-4 font-medium text-[#1C1917]">
          Say it. Don't assume they know.
        </p>

        <!-- Section 3 -->
        <h2 class="article-h2 mt-12">Twelve things that actually work</h2>
        <p class="article-p">
          Once you've told them why it matters, here are the approaches that consistently unlock even the most private parents.
        </p>

        <div class="mt-8 space-y-6">

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">1. Ask specific questions, not open ones</h3>
            <p class="article-p mt-2">
              "Tell me about your life" produces silence. "What did your childhood home smell like?" produces a story. The more specific the question, the easier it is to answer — and the more detail tends to come out.
            </p>
            <div class="mt-3 rounded-2xl bg-[#FAF7F4] border border-[#E8DDD0] px-5 py-4">
              <p class="text-xs font-medium text-[#9C7C5C] mb-2">INSTEAD OF → TRY THIS</p>
              <div class="space-y-2 text-sm">
                <div class="flex gap-3">
                  <span class="text-stone-400 flex-shrink-0">✗</span>
                  <div>
                    <p class="text-stone-400 line-through">Tell me about your childhood</p>
                    <p class="text-[#3C3530] mt-0.5">✓ What did you have for breakfast when you were little?</p>
                  </div>
                </div>
                <div class="flex gap-3">
                  <span class="text-stone-400 flex-shrink-0">✗</span>
                  <div>
                    <p class="text-stone-400 line-through">What were your dreams?</p>
                    <p class="text-[#3C3530] mt-0.5">✓ What did you want to be when you were about ten years old?</p>
                  </div>
                </div>
                <div class="flex gap-3">
                  <span class="text-stone-400 flex-shrink-0">✗</span>
                  <div>
                    <p class="text-stone-400 line-through">What was it like being a parent?</p>
                    <p class="text-[#3C3530] mt-0.5">✓ What do you remember about the day I was born?</p>
                  </div>
                </div>
              </div>
            </div>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">2. Ask side by side, not face to face</h3>
            <p class="article-p mt-2">
              Face to face feels like an interview. Side by side — in a car, on a walk, at the kitchen table while you're both doing something else — feels like a conversation. The absence of eye contact removes pressure in a way that's hard to overstate, especially for private people.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">3. Use photos as a doorway</h3>
            <p class="article-p mt-2">
              An old family photo is one of the most powerful memory triggers there is. Sit with them and go through an old album. "Who's this?" or "What was happening here?" costs nothing — and can open up hours of conversation you'd never have reached with a direct question.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">4. Start with their achievements, not their feelings</h3>
            <p class="article-p mt-2">
              Many parents — fathers especially — find questions about emotions or inner life uncomfortable. But questions about what they did, what they built, what they achieved? Those are much easier. Start there. The feelings often surface naturally once they're in the flow of talking.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">5. Let silence sit</h3>
            <p class="article-p mt-2">
              The instinct when someone goes quiet is to fill the silence — to rephrase the question, or move on, or apologise for asking. Resist that instinct. Some of the best answers come after a long pause. The silence means they're thinking, not refusing.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">6. Offer writing as an alternative to talking</h3>
            <p class="article-p mt-2">
              Some people find it far easier to write than to speak about personal things. They can take their time, choose their words, go back and change things. If your parent finds conversation uncomfortable, give them the questions and let them answer in writing — in their own time, without an audience.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">7. Ask about other people, not themselves</h3>
            <p class="article-p mt-2">
              "What were your parents like?" is often easier than "what were you like?" Asking about other people first — grandparents, siblings, friends — is a back door into their own story. Their answers inevitably reveal as much about them as about the people they're describing.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">8. Spread it across many visits</h3>
            <p class="article-p mt-2">
              Don't try to capture everything in one sitting. A few questions per visit, over weeks or months, builds something richer than any single session — and it gives them time to think between visits. Many parents come back the next time having remembered something new.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">9. Follow tangents</h3>
            <p class="article-p mt-2">
              If they start telling you something you didn't ask about, follow it. The unplanned stories are usually the best ones. Staying rigidly on your list of questions misses the point entirely.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">10. Accept partial answers</h3>
            <p class="article-p mt-2">
              Not every question will get a full answer. Some things are private. Some memories are painful. Some doors stay closed. Accept what they give you without pushing. The trust you build by respecting their limits is what opens the harder questions later.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">11. Share something of your own first</h3>
            <p class="article-p mt-2">
              Vulnerability invites vulnerability. If you share something personal before asking them to — a worry, a memory, something you've been thinking about — it changes the emotional temperature of the conversation. It signals that this is a safe space.
            </p>
          </div>

          <div>
            <h3 class="font-semibold text-[#1C1917] text-base">12. Involve the grandchildren</h3>
            <p class="article-p mt-2">
              Many grandparents who resist talking to their adult children will open up completely when a grandchild asks. There's something about a grandchild's genuine curiosity — "Grandad, what were you like when you were my age?" — that bypasses every defence. If you have children, use them.
            </p>
          </div>

        </div>

        <!-- Section 4 -->
        <h2 class="article-h2 mt-12">When a parent really won't engage</h2>
        <p class="article-p">
          Sometimes, despite everything, a parent simply won't talk. The reasons can be deep — trauma, shame, a lifetime of privacy, or cognitive decline that makes the past inaccessible.
        </p>
        <p class="article-p mt-4">
          In those cases, here's what you can still do:
        </p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">Capture what you already know</p>
            <p class="tip-desc">Write down everything you already know about their life — the stories you've heard before, the things other family members have mentioned, the details you've absorbed over a lifetime. That's a story too, and it's worth preserving.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Ask other relatives</p>
            <p class="tip-desc">Aunts, uncles, siblings, old family friends — people who knew your parent before you did. They often hold pieces of the story your parent would never tell you directly.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Look for documents and photos</p>
            <p class="tip-desc">Letters, diaries, certificates, old photos — these are the fragments of a life. Even without words, they tell a story. Scanning and preserving them is an act of memory in itself.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Keep the door open</p>
            <p class="tip-desc">People change. A parent who won't talk today might be ready in a year, or after a health scare, or at a different time of life. Don't close the door — just leave it open and return to it gently.</p>
          </div>
        </div>

