        <!-- Section 1 -->
        <h2 class="article-h2 mt-12">What is a memorial tribute video?</h2>
        <p class="article-p">
          A memorial tribute video — sometimes called a funeral slideshow, a life tribute, or a celebration of life video — is a short video that tells the story of someone's life through their photos, set to music that was meaningful to them.
        </p>
        <p class="article-p mt-4">
          They're typically played at the funeral service, at the wake afterwards, or shared with family members who couldn't attend. They can also be kept as a permanent digital record — something the family can watch together for years to come.
        </p>
        <p class="article-p mt-4">
          A good tribute video doesn't need to be long or complicated. 10 to 20 photos, the right music, and a short message from the family is enough to create something genuinely moving.
        </p>

        <!-- Section 2 -->
        <h2 class="article-h2 mt-12">Step 1 — Gather the photos</h2>
        <p class="article-p">
          This is usually the hardest step — not technically, but emotionally. Going through someone's photos when you're grieving is difficult. Here's how to approach it.
        </p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">Ask multiple family members</p>
            <p class="tip-desc">Different relatives will have different photos from different eras. A sibling might have childhood photos. A child might have recent ones. A friend might have photos from a part of their life you never saw. Cast the net wide.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Use your phone's shared album feature</p>
            <p class="tip-desc">Create a shared album on iCloud or Google Photos and send the link to family members. They can add photos directly without emailing files back and forth. It's the fastest way to collect photos from multiple people quickly.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Scan physical photos if needed</p>
            <p class="tip-desc">For older relatives, the best photos are often physical prints. A phone camera pointed at a flat photo in good light is enough — you don't need a scanner. The Microsoft Lens app (free) does this particularly well.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Aim for 15-25 photos</p>
            <p class="tip-desc">More isn't always better. 15-25 well-chosen photos tells a fuller story than 50 random ones. Try to include photos from across their whole life — childhood, young adulthood, family life, and recent years.</p>
          </div>
        </div>

        <!-- Section 3 -->
        <h2 class="article-h2 mt-12">Step 2 — Choose the order</h2>
        <p class="article-p">
          Chronological order — from earliest to most recent — almost always works best for a tribute video. It tells the story of a life from beginning to end, which gives the video a natural emotional arc.
        </p>
        <p class="article-p mt-4">
          A few things worth thinking about:
        </p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">Open with a striking photo</p>
            <p class="tip-desc">The first photo sets the tone for everything that follows. A clear, well-lit photo of their face — from any era — tends to work best as the opening frame.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">End with something recent and warm</p>
            <p class="tip-desc">The final photo is the one people will sit with longest. A photo of them laughing, surrounded by family, or doing something they loved tends to leave the right feeling.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Group photos by chapter</p>
            <p class="tip-desc">Childhood photos together, then young adult years, then family life, then later years. Even without titles or text, this creates a sense of a life unfolding naturally.</p>
          </div>
        </div>

        <!-- Section 4 -->
        <h2 class="article-h2 mt-12">Step 3 — Write the tribute message</h2>
        <p class="article-p">
          A short tribute message — a paragraph or two — becomes a beautiful quote slide woven through the video. It doesn't need to be long or perfectly written. It just needs to be true.
        </p>
        <p class="article-p mt-4">
          If you're struggling to write it, here are some prompts that help:
        </p>

        <div class="mt-6 rounded-2xl border border-[#E8DDD0] bg-[#FAF7F4] px-6 py-6">
          <p class="text-sm font-medium text-[#1C1917] mb-4">Things worth including in a tribute:</p>
          <div class="space-y-2">
            <p class="text-sm text-[#3C3530] flex gap-2"><span class="text-[#9C7C5C] flex-shrink-0">✦</span> What they were like — a few words that capture their personality</p>
            <p class="text-sm text-[#3C3530] flex gap-2"><span class="text-[#9C7C5C] flex-shrink-0">✦</span> What they loved — people, places, things, hobbies</p>
            <p class="text-sm text-[#3C3530] flex gap-2"><span class="text-[#9C7C5C] flex-shrink-0">✦</span> What they gave to others — how they made people feel</p>
            <p class="text-sm text-[#3C3530] flex gap-2"><span class="text-[#9C7C5C] flex-shrink-0">✦</span> What they would want to be remembered for</p>
            <p class="text-sm text-[#3C3530] flex gap-2"><span class="text-[#9C7C5C] flex-shrink-0">✦</span> A sentence that feels like them — something they'd say, or something only your family would know</p>
          </div>
        </div>

        <p class="article-p mt-6">
          You don't have to write it alone. Ask a family member to contribute a line. Sometimes the best tributes are written together.
        </p>

        <!-- Section 5 -->
        <h2 class="article-h2 mt-12">Step 4 — Choose the music</h2>
        <p class="article-p">
          The music carries more emotional weight than almost anything else in a tribute video. The right song can make a room full of people cry. The wrong one can feel jarring.
        </p>
        <p class="article-p mt-4">
          The best approach is to use music that was meaningful to them — a song they loved, something from their era, or a piece of music associated with a memory your family shares.
        </p>

        <div class="mt-6 space-y-4">
          <div class="tip-card">
            <p class="tip-title">Ask family what music they loved</p>
            <p class="tip-desc">Even if you don't know the specific song, someone in the family will. A piece of music from their youth, their wedding song, or something they always had on — these choices feel personal in a way that generic music never does.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Instrumental tends to work better than vocal</p>
            <p class="tip-desc">Songs with lyrics compete with people's thoughts and emotions. A piano piece, a string arrangement, or an instrumental version of a favourite song lets people feel without distraction.</p>
          </div>
          <div class="tip-card">
            <p class="tip-title">Match the pace to the mood</p>
            <p class="tip-desc">A celebration of life for someone who lived fully and joyfully can handle something warmer and more uplifting. A funeral service for someone taken too soon needs something quieter and more contemplative.</p>
          </div>
        </div>

