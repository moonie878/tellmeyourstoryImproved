          <p class="founder-text">
            When someone you love dies, the last thing you want to think about is technology. But a memorial tribute video — a slideshow of their photos set to music — is one of the most moving things you can do to honour their life at a funeral, wake, or celebration of life.
          </p>
          <p class="founder-text mt-4">
            This guide walks you through exactly how to create one. What photos to use, how to organise them, what music to choose, and how to have it ready in time — even if you have very little time.
